const grid = document.getElementById("grid");
const search = document.getElementById("search");
const tabs = document.querySelectorAll(".tab");

let currentCategory = "imo";


function renderCommunities() {

    const searchTerm = search.value.toLowerCase();


    const filtered = communities.filter(function(community) {

        const matchesCategory =
            community.category === currentCategory;


        const matchesSearch =
            community.name.toLowerCase().includes(searchTerm) ||
            community.location.toLowerCase().includes(searchTerm);


        return matchesCategory && matchesSearch;

    });


    grid.innerHTML = "";


    filtered.forEach(function(community) {

        const card = document.createElement("div");

        card.className = "card";


        if (community.link) {

            card.innerHTML = `
                <div>

                    <h3>${community.name}</h3>

                    <small>${community.location}</small>

                </div>

                <a
                    href="${community.link}"
                    target="_blank"
                    rel="noopener noreferrer"
                >
                    Join Group
                </a>
            `;

        } else {

            card.classList.add("pending");


            card.innerHTML = `
                <div>

                    <h3>${community.name}</h3>

                    <small>${community.location}</small>

                </div>

                <span>Coming Soon</span>
            `;

        }


        grid.appendChild(card);

    });


}


tabs.forEach(function(tab) {

    tab.addEventListener("click", function() {

        tabs.forEach(function(item) {

            item.classList.remove("active");

        });


        this.classList.add("active");


        currentCategory =
            this.dataset.category;


        search.value = "";


        renderCommunities();

    });

});


search.addEventListener("input", function() {

    renderCommunities();

});


renderCommunities();


